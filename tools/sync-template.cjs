const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const source = JSON.parse(fs.readFileSync(path.join(root, 'data/cde-template.json'), 'utf8'));
const output = '/* Generated by node tools/sync-template.cjs; edit cde-template.json. */\nwindow.CDE_TEMPLATE = ' + JSON.stringify(source, null, 2).replace(/</g, '\\u003c') + ';\n';
fs.writeFileSync(path.join(root, 'data/template.js'), output);
console.log('Synced canonical offline template');
